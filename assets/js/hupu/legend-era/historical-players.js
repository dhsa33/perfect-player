/** 历史时代：该球员真实退役起始年份（en 或 cname 匹配；找不到返回 null，走通用年龄曲线） */
function getHistoricalRetireYear(p) {
  if (!p) return null;
  var en = p.nameEN || p.name || '';
  if (HISTORICAL_RETIRE_YEARS[en] != null) return HISTORICAL_RETIRE_YEARS[en];
  var cn = p.cname || '';
  var keys = Object.keys(HISTORICAL_RETIRE_YEARS);
  for (var i = 0; i < keys.length; i++) {
    if (HISTORICAL_PLAYERS && HISTORICAL_PLAYERS.some) {
      // 按中文名兜底匹配（避免别名差异）
      var found = HISTORICAL_PLAYERS.some(function(h) { return h.en === keys[i] && h.cn === cn; });
      if (found) return HISTORICAL_RETIRE_YEARS[keys[i]];
    }
  }
  return null;
}
