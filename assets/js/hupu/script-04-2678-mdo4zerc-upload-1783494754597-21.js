function getHeadshotStyle(playerName, displaySize = 30) {
  const pos = SPRITE_POS[playerName];
  if (!pos) return "";
  const scale = displaySize / 300;
  const sheetW = 1800;
  const sheetH = 1800;
  const file = SPRITE_FILES[pos.sheet];
  const bgX = Math.round(pos.x * scale) + 1;
  const bgY = Math.round(pos.y * scale);
  const bgW = Math.round(sheetW * scale);
  return `background-image:url(${file});background-size:${bgW}px ${bgW}px;background-position:-${bgX}px -${bgY}px;background-repeat:no-repeat;width:${displaySize}px;height:${displaySize}px;`;
}